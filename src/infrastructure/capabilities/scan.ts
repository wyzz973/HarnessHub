  private async hooks(table: HarnessReadTable, harnessName: string): Promise<void> {
    for (const source of table.hooks ?? []) {
      for (const hook of await this.hookList(table.harnessId, source)) {
        const row = this.row("hook", "hook:" + hook.key, hook.name, () => ({ description: hook.program, owner: "user", source: null, location: hook.via, facts: { kind: "hook", event: hook.event, matcher: hook.matcher, program: hook.program } }));
        row.edges.push({ harnessId: table.harnessId, mechanism: source.role === "compat" ? "compat-root" : "config", status: hook.enabled ? "active" : "disabled", via: hook.via, reason: hook.enabled ? hookNote(table.harnessId) : harnessName + " 的配置里停用了它" });
        if (source.role === "compat") row.warnings.push({ kind: "cross", harnessId: table.harnessId, text: harnessName + " 默认也会运行这个 Hook（来自 " + hook.via + "）。" });
      }
    }
  }
  private async hookList(harnessId: string, source: HookSource): Promise<readonly { key: string; name: string; event: string; matcher: string | null; program: string | null; via: string; enabled: boolean }[]> {
    const via = this.shown(source.file), out: { key: string; name: string; event: string; matcher: string | null; program: string | null; via: string; enabled: boolean }[] = [];
    if (source.style === "openclaw-dirs") {
      const entries = record(at(await this.value(harnessId, harnessDirectories(this.environment).openclawConfig, "json5"), ["hooks", "internal", "entries"]));
      let items; try { items = await readdir(source.file, { withFileTypes: true }); } catch { return []; }
      for (const item of items.sort((left, right) => left.name < right.name ? -1 : 1).slice(0, MAX_LISTED_FILES)) {
        if (item.name.startsWith(".") || !(item.isDirectory() || item.isSymbolicLink())) continue;
        const file = await this.read(join(source.file, item.name, "HOOK.md"), MAX_DOCUMENT_BYTES);
        if (file.state !== "ok") continue;
        const fields = frontmatter(file.text).value ?? {}, configured = text(fields.name) ?? item.name, name = this.clean(configured), events = strings(fields.events).map(event => this.clean(event));
        out.push({ key: via + "#" + item.name, name, event: events.join("、") || "（HOOK.md 未写事件）", matcher: null, program: null, via: this.shown(join(source.file, item.name)), enabled: record(own(entries, configured)).enabled !== false });
      }
      return out;
    }
    const format: ConfigFormat = source.style === "codex-toml" ? "toml" : source.style === "hermes" ? "yaml" : "json";
    const value = await this.value(harnessId, source.file, format), hooks = record(at(value, ["hooks"]));
    for (const [configured, list] of Object.entries(hooks)) {
      if (!Array.isArray(list)) continue;
      const event = this.clean(configured);
      list.slice(0, 256).forEach((group, index) => {
        const item = record(group), nested = Array.isArray(item.hooks) ? item.hooks.map(record) : [item], matcher = this.clean(text(item.matcher));
        nested.slice(0, 64).forEach((hook, inner) => {
          const command = text(hook.command) ?? strings(hook.command)[0] ?? null;
          if (command === null && text(hook.type) !== "command" && hook.type !== undefined) return;
          out.push({ key: via + "#" + event + "#" + index + "." + inner, name: event + (matcher ? "（" + matcher + "）" : ""), event, matcher, program: programName(command), via, enabled: hook.enabled !== false && item.enabled !== false });
        });
      });
    }
    return out;
  }

