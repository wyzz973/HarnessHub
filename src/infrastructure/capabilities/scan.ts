async function skillSize(path: string): Promise<{ files: number; bytes: number }> {
  let files = 0, bytes = 0, visited = 0;
  const walk = async (dir: string, level: number): Promise<void> => {
    let items; try { items = await readdir(dir, { withFileTypes: true }); } catch { return; }
    for (const item of items) {
      if (++visited > MAX_SKILL_WALK || level > 8) return;
      const entry = join(dir, item.name);
      if (item.isDirectory()) await walk(entry, level + 1);
      else if (item.isFile()) { files++; bytes += (await lstat(entry).catch(() => null))?.size ?? 0; }
    }
  };
  await walk(path, 1);
  return { files, bytes };
}
