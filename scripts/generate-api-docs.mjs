import { mkdtemp, readFile, writeFile, rm, mkdir } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { checkApiCatalog } from "./check-api-docs.mjs";
const root = fileURLToPath(new URL("../", import.meta.url));
const { startHub } = await import("../dist/src/main.js");
const { apiCatalog } = await import("../dist/src/gateway/api-catalog.js");
if (process.argv.slice(2).some((arg) => arg !== "--check"))
  throw new Error(
    "Usage: node scripts/generate-api-docs.mjs [--check] (build first)",
  );
const directory = await mkdtemp(path.join(os.tmpdir(), "harnesshub-api-docs-"));
let hub;
try {
  hub = await startHub({
    cwd: directory,
    dataDir: directory,
    demo: true,
    port: 0,
  });
  const spec = hub.server.swagger();
  const count = await checkApiCatalog(apiCatalog, spec, root);
  let markdown =
    "# HTTP API 实现参考\n\n<!-- Generated by pnpm docs:api. Edit src/gateway/api-catalog.ts and route schemas instead. -->\n\n本页由正式 Gateway 路由与实现说明生成，共 " +
    count +
    " 个 HTTP 操作（不重复列自动 HEAD）。参数结构以 [OpenAPI JSON](openapi.json)和路由 schema 为准。错误、对象含义和示例见 [API 入口](README.md)。\n\n";
  markdown += "| 方法 | 路径 | 用途 |\n|---|---|---|\n";
  for (const e of apiCatalog)
    markdown += `| ${e.method} | [\`${e.path}\`](#${e.operationId}) | ${e.title} |\n`;
  for (const e of apiCatalog) {
    const op = spec.paths[e.path][e.method.toLowerCase()];
    const inputs = (op.parameters ?? [])
      .map((p) => `${p.in}: ${p.name}${p.required ? "（必需）" : ""}`)
      .join("；");
    markdown += `\n## ${e.operationId}\n\n**${e.method} \`${e.path}\` — ${e.title}**\n\n- 输入：${e.request}\n- 返回：${e.response}\n- 实现链路：${e.implementation}\n- 持久化与副作用：${e.effects}\n- 失败与边界：${e.errors}\n`;
    if (inputs) markdown += `- Schema 参数索引：${inputs}。\n`;
    markdown += `\n实现入口：[${e.source}](../../${e.source})。验证依据：${e.tests.map((t) => `[${t}](../../${t})`).join("、")}。\n`;
  }
  const outputs = new Map([
    ["docs/api/openapi.json", JSON.stringify(spec, null, 2) + "\n"],
    ["docs/api/reference.md", markdown],
  ]);
  for (const [file, content] of outputs) {
    const target = path.join(root, file);
    if (process.argv.includes("--check")) {
      if ((await readFile(target, "utf8")) !== content)
        throw new Error(`${file} is stale; run pnpm docs:api`);
    } else {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, content);
    }
  }
  console.log(
    `${count} HTTP operations documented; schemas and implementation pointers ${process.argv.includes("--check") ? "verified" : "generated"}. No engines or models called.`,
  );
} finally {
  try {
    await hub?.server.close();
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}
